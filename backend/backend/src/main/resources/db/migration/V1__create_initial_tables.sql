
-- V1: Khoi tao co so du lieu Hoa Khanh Rental

-- 1. Tai khoan
CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       full_name VARCHAR(150) NOT NULL,
                       email VARCHAR(255) NOT NULL UNIQUE,
                       password_hash VARCHAR(255) NOT NULL,
                       phone VARCHAR(20),
                       role VARCHAR(20) NOT NULL
                           CHECK (role IN ('STUDENT', 'LANDLORD', 'ADMIN')),
                       is_active BOOLEAN NOT NULL DEFAULT TRUE,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Ho so sinh vien
CREATE TABLE student_profiles (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  user_id BIGINT NOT NULL UNIQUE
                                      REFERENCES users(id),
                                  university VARCHAR(200),
                                  student_code VARCHAR(50),
                                  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Ho so chu tro
CREATE TABLE landlord_profiles (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   user_id BIGINT NOT NULL UNIQUE
                                       REFERENCES users(id),
                                   contact_address VARCHAR(255),
                                   description TEXT,
                                   created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. Phong tro
CREATE TABLE rooms (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       landlord_id BIGINT NOT NULL
                           REFERENCES users(id),
                       title VARCHAR(200) NOT NULL,
                       description TEXT,
                       address VARCHAR(255) NOT NULL,
                       area_name VARCHAR(150),
                       price NUMERIC(12, 2) NOT NULL
                           CHECK (price >= 0),
                       area_sqm NUMERIC(8, 2) NOT NULL
                           CHECK (area_sqm > 0),
                       max_occupants INTEGER NOT NULL DEFAULT 1
                           CHECK (max_occupants > 0),

                       moderation_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                           CHECK (moderation_status IN
                                  ('PENDING', 'APPROVED', 'REJECTED')),

                       occupancy_status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE'
                           CHECK (occupancy_status IN
                                  ('AVAILABLE', 'RENTED')),

                       visibility_status VARCHAR(20) NOT NULL DEFAULT 'VISIBLE'
                           CHECK (visibility_status IN
                                  ('VISIBLE', 'HIDDEN')),

                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       deleted_at TIMESTAMPTZ
);

-- 5. Hinh anh phong tro
CREATE TABLE room_images (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             room_id BIGINT NOT NULL
                                 REFERENCES rooms(id) ON DELETE CASCADE,
                             image_url TEXT NOT NULL,
                             is_cover BOOLEAN NOT NULL DEFAULT FALSE,
                             sort_order INTEGER NOT NULL DEFAULT 0,
                             created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 6. Phong yeu thich
CREATE TABLE favorites (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           student_id BIGINT NOT NULL
                               REFERENCES users(id),
                           room_id BIGINT NOT NULL
                               REFERENCES rooms(id) ON DELETE CASCADE,
                           created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           CONSTRAINT uq_favorite_student_room
                               UNIQUE (student_id, room_id)
);

-- 7. Yeu cau lien he
CREATE TABLE contact_requests (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  student_id BIGINT NOT NULL
                                      REFERENCES users(id),
                                  room_id BIGINT NOT NULL
                                      REFERENCES rooms(id),
                                  message TEXT,
                                  status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                                      CHECK (status IN
                                             ('PENDING', 'RESPONDED', 'CLOSED')),
                                  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Index ho tro tim kiem va truy van
CREATE INDEX idx_rooms_landlord
    ON rooms(landlord_id);

CREATE INDEX idx_rooms_price
    ON rooms(price);

CREATE INDEX idx_rooms_status
    ON rooms(moderation_status, occupancy_status, visibility_status);

CREATE INDEX idx_rooms_area
    ON rooms(area_name);

CREATE INDEX idx_room_images_room
    ON room_images(room_id);

CREATE INDEX idx_favorites_student
    ON favorites(student_id);

CREATE INDEX idx_contact_requests_room
    ON contact_requests(room_id);

CREATE INDEX idx_contact_requests_student
    ON contact_requests(student_id);
